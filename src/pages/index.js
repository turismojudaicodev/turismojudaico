export async function getStaticProps({ locale }) {
  const tours = await prisma.tour.findMany({ where: { active: true, locale } })

  return {
    props: {
      ...(await serverSideTranslations(locale, ['index', 'common'])),
      tours: JSON.parse(JSON.stringify(tours)),
      locale,
    },
  }
}

